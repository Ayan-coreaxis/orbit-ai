// Bundles the site-craft skill (D:/site-craft by default) into lib/site-craft-skill.ts so the
// store builder can use it in production. Re-run after editing the skill:
//   node scripts/bundle-site-craft.mjs [path-to-skill]
import fs from "node:fs";
import path from "node:path";
const root = process.argv[2] || "D:/site-craft";
const FILES = [
  "SKILL.md",
  "references/art-direction.md",
  "references/anti-patterns.md",
  "references/studio-grade.md",
  "references/site-types/ecommerce.md",
  "references/foundations.md",
  "references/color.md",
  "references/components.md",
  "references/motion.md",
  "references/styles.md",
  "references/qa-checklist.md",
];
const parts = FILES.map((f) => `<file path="${f}">\n${fs.readFileSync(path.join(root, f), "utf8").trim()}\n</file>`);
const out = `// GENERATED by scripts/bundle-site-craft.mjs from the site-craft skill — do not edit by hand.
export const SITE_CRAFT_SKILL: string = ${JSON.stringify(parts.join("\n\n"))};
`;
fs.writeFileSync(new URL("../lib/site-craft-skill.ts", import.meta.url), out);
console.log("wrote lib/site-craft-skill.ts", out.length, "chars");
